// Emoji chu cu (bo FE0F) -> id sticker, dung khi doi overlay emoji cu sang sticker
const STICKER_BY_CHAR = new Map(STICKER_GROUPS.flatMap((group) => group.items.map((item) => [item.char, item.id])))
export function stickerIdForChar(char) { return STICKER_BY_CHAR.get(String(char).replace(/\uFE0F/g, '')) || null }

export function stickerChar(id) { return STICKER_GROUPS.flatMap((group) => group.items).find((item) => item.id === id)?.char || null }

// URL tuong doi voi trang hien tai (dev: http://localhost, build: file:// -> dist)
export function stickerUrl(id) { return new URL(`stickers/${id}.png`, document.baseURI).href }
