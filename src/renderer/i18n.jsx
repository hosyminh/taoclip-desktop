const I18nCtx = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('taoclip_lang') || 'vi')
  const change = useCallback((l) => { setLang(l); localStorage.setItem('taoclip_lang', l) }, [])
  const t = useCallback((key, vars) => {
    let s = (STR[lang] && STR[lang][key]) ?? STR.vi[key] ?? key
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k])
    return s
  }, [lang])
  return <I18nCtx.Provider value={{ t, lang, setLang: change }}>{children}</I18nCtx.Provider>
}

export const useI18n = () => useContext(I18nCtx)
